-- Supertipo da especializacao dos papeis.
CREATE TABLE usuario (
    id_usuario                 INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nm_usuario                 VARCHAR(150) NOT NULL,
    nr_cpf_cnpj                VARCHAR(14),
    ds_email                   VARCHAR(150),
    ds_senha_hash              VARCHAR(255),
    id_origem                  INTEGER,
    fl_ativo                   BOOLEAN NOT NULL DEFAULT TRUE,
    dt_cadastro                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dt_anonimizacao            TIMESTAMP,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_usuario_nr_cpf_cnpj UNIQUE (nr_cpf_cnpj),
    CONSTRAINT uk_usuario_ds_email UNIQUE (ds_email)
);

