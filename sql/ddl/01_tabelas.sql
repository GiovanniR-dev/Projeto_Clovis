    CONSTRAINT pk_imovel PRIMARY KEY (id_imovel),
    CONSTRAINT uk_imovel_cd_imobizi UNIQUE (cd_imobizi),
    CONSTRAINT ck_imovel_tp_finalidade CHECK (tp_finalidade IN ('venda', 'locacao', 'ambas')),
