    id_imovel                  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cd_imobizi                 VARCHAR(30),
    id_proprietario            INTEGER NOT NULL,
    id_corretor_responsavel    INTEGER,
    nr_cep                     CHAR(8) NOT NULL,
    id_tipo_imovel             INTEGER NOT NULL,
    tp_finalidade              VARCHAR(10) NOT NULL,
    nm_logradouro              VARCHAR(150) NOT NULL,
    nr_endereco                VARCHAR(10) NOT NULL,
    ds_complemento             VARCHAR(60),
    id_bairro                  INTEGER NOT NULL,
    vl_area_util               NUMERIC(10,2),
    vl_area_total              NUMERIC(10,2),
    qt_quartos                 SMALLINT,
    qt_banheiros               SMALLINT,
    qt_vagas_garagem           SMALLINT,
    vl_venda                   NUMERIC(12,2),
    vl_aluguel                 NUMERIC(12,2),
