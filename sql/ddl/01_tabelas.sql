-- Dominio: as 27 unidades federativas (antes a sigla era texto livre em cidade).
CREATE TABLE uf (
    sg_uf                      CHAR(2) NOT NULL,
    nm_uf                      VARCHAR(30) NOT NULL,
    CONSTRAINT pk_uf PRIMARY KEY (sg_uf),
    CONSTRAINT uk_uf_nm_uf UNIQUE (nm_uf),
    CONSTRAINT ck_uf_sg_uf CHECK (sg_uf ~ '^[A-Z]{2}$')
);

-- 3FN: cidade e UF ficam aqui, e nao no imovel.
CREATE TABLE cidade (
    id_cidade                  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nm_cidade                  VARCHAR(100) NOT NULL,
    sg_uf                      CHAR(2) NOT NULL,
    CONSTRAINT pk_cidade PRIMARY KEY (id_cidade),
    CONSTRAINT uk_cidade_nm_cidade_sg_uf UNIQUE (nm_cidade, sg_uf)
);

-- 3FN: CEP -> cidade e UF.
CREATE TABLE cep (
    nr_cep                     CHAR(8) NOT NULL,
    id_cidade                  INTEGER NOT NULL,
    tp_cep                     VARCHAR(15) NOT NULL,
    CONSTRAINT pk_cep PRIMARY KEY (nr_cep),
    CONSTRAINT ck_cep_tp_cep CHECK (tp_cep IN ('geral', 'logradouro'))
);

-- Dominio: bairros de cada cidade (antes um texto repetido em imovel e em perfil_interesse) (RN51).
CREATE TABLE bairro (
    id_bairro                  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cidade                  INTEGER NOT NULL,
    nm_bairro                  VARCHAR(100) NOT NULL,
    CONSTRAINT pk_bairro PRIMARY KEY (id_bairro),
    CONSTRAINT uk_bairro_id_cidade_nm_bairro UNIQUE (id_cidade, nm_bairro)
);

-- Entidade fraca do CLIENTE.
CREATE TABLE perfil_interesse (
    id_usuario                 INTEGER NOT NULL,
    nr_perfil                  SMALLINT NOT NULL,
    id_cidade                  INTEGER,
    tp_finalidade              VARCHAR(10) NOT NULL,
    vl_minimo                  NUMERIC(12,2),
    vl_maximo                  NUMERIC(12,2),
    qt_quartos_min             SMALLINT,
    CONSTRAINT pk_perfil_interesse PRIMARY KEY (id_usuario, nr_perfil),
    CONSTRAINT ck_perfil_interesse_tp_finalidade CHECK (tp_finalidade IN ('venda', 'locacao')),
    CONSTRAINT ck_perfil_interesse_vl_minimo_vl_maximo CHECK (vl_minimo IS NULL OR vl_maximo IS NULL OR vl_minimo <= vl_maximo)
);

-- Relacionamento N:N DESEJA: os tipos de imovel aceitos pelo perfil; perfil sem tipo aceita qualquer tipo (RN47).
CREATE TABLE perfil_interesse_tipo (
