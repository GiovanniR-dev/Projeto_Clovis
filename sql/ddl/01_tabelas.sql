    CONSTRAINT ck_proposta_id_autorizador_vl_proposto CHECK (vl_proposto >= 0.9 * vl_anunciado OR (id_autorizador IS NOT NULL AND dt_autorizacao IS NOT NULL)),
    CONSTRAINT ck_proposta_id_proposta_id_proposta_respondida CHECK (id_proposta_respondida IS NULL OR id_proposta_respondida <> id_proposta)
);

-- vl_corretagem = vl_final x pc_corretagem e derivado e nao e armazenado.
CREATE TABLE contrato (
    id_contrato                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_proposta                INTEGER NOT NULL,
    tp_contrato                VARCHAR(10) NOT NULL,
    tp_condicao_pagamento      VARCHAR(20) NOT NULL,
    vl_final                   NUMERIC(12,2) NOT NULL,
    pc_corretagem              NUMERIC(5,2) NOT NULL,
    pc_administracao           NUMERIC(5,2),
    nr_dia_vencimento          SMALLINT,
    dt_assinatura              DATE,
    dt_inicio                  DATE,
    dt_fim                     DATE,
    st_contrato                VARCHAR(12) NOT NULL DEFAULT 'rascunho',
    dt_termino                 DATE,
    ds_motivo_termino          TEXT,
    tp_iniciativa_rescisao     VARCHAR(15),
    CONSTRAINT pk_contrato PRIMARY KEY (id_contrato),
    CONSTRAINT uk_contrato_id_proposta UNIQUE (id_proposta),
    CONSTRAINT ck_contrato_tp_contrato CHECK (tp_contrato IN ('venda', 'locacao')),
    CONSTRAINT ck_contrato_tp_condicao_pagamento CHECK (tp_condicao_pagamento IN ('a_vista', 'financiado', 'parcelado_direto')),
    CONSTRAINT ck_contrato_st_contrato CHECK (st_contrato IN ('rascunho', 'vigente', 'encerrado', 'rescindido', 'cancelado')),
    CONSTRAINT ck_contrato_pc_corretagem CHECK (pc_corretagem >= 0 AND pc_corretagem <= 100),
    CONSTRAINT ck_contrato_pc_administracao CHECK (pc_administracao IS NULL OR (pc_administracao >= 0 AND pc_administracao <= 100)),
    CONSTRAINT ck_contrato_tp_contrato_pc_administracao CHECK (tp_contrato <> 'locacao' OR (dt_inicio IS NOT NULL AND dt_fim IS NOT NULL AND pc_administracao IS NOT NULL AND nr_dia_vencimento IS NOT NULL)),
    CONSTRAINT ck_contrato_dt_assinatura_st_contrato CHECK (st_contrato NOT IN ('vigente', 'encerrado', 'rescindido') OR dt_assinatura IS NOT NULL),
    CONSTRAINT ck_contrato_st_contrato_dt_termino CHECK ((st_contrato IN ('encerrado', 'rescindido', 'cancelado')) = (dt_termino IS NOT NULL)),
    CONSTRAINT ck_contrato_st_contrato_ds_motivo_termino CHECK (st_contrato NOT IN ('rescindido', 'cancelado') OR ds_motivo_termino IS NOT NULL),
    CONSTRAINT ck_contrato_st_contrato_tp_iniciativa_rescisao CHECK ((st_contrato = 'rescindido') = (tp_iniciativa_rescisao IS NOT NULL)),
    CONSTRAINT ck_contrato_tp_iniciativa_rescisao CHECK (tp_iniciativa_rescisao IN ('cliente', 'proprietario', 'comum_acordo'))
);

