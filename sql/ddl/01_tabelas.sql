    id_imovel                  INTEGER NOT NULL,
    id_cliente                 INTEGER NOT NULL,
    id_corretor                INTEGER NOT NULL,
    id_autorizador             INTEGER,
    id_proposta_respondida     INTEGER,
    id_visita                  INTEGER,
    vl_proposto                NUMERIC(12,2) NOT NULL,
    vl_anunciado               NUMERIC(12,2) NOT NULL,
    ds_condicoes               TEXT,
